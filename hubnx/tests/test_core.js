const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const path=require('node:path');
const src=fs.readFileSync(path.join(__dirname,'..','index.html'),'utf8');
const js=src.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(js,'JS do app encontrado');
const replacement='globalThis.__test={safeURL,normalize,compare,sanitize,defaults,now};\n})();';
const cut=js.indexOf('window.HubNX={');
assert.ok(cut>0,'Inicialização localizada');
const isolated=js.slice(0,cut)+replacement;
assert.notEqual(js,isolated,'Código de inicialização removido somente no teste');
const context={URL,Date,console};context.window=context;
vm.runInNewContext(isolated,context);
const {safeURL,normalize,compare,sanitize}=context.__test;
assert.equal(safeURL('https://webcinevs2.com/'),'https://webcinevs2.com/');
assert.equal(safeURL('http://example.com/test'),'http://example.com/test');
assert.equal(safeURL('javascript:alert(1)'),null);
assert.equal(safeURL('data:text/html,hi'),null);
assert.equal(safeURL('https://admin:secret@example.com'),null);
assert.equal(safeURL('file:///android_asset/index.html'),null);
assert.equal(compare('0.2.0','0.1.9'),1);
assert.equal(compare('0.1.0','0.1.0'),0);
assert.equal(compare('0.0.9','0.1.0'),-1);
assert.equal(compare('garbage','0.1.0'),0);
const clean=normalize([{id:'A',name:'CineVS',url:'https://example.com',order:3},{id:'A',name:'Duplicado',url:'https://other.org',order:4},{id:'B',name:'Teste',url:'javascript:alert(1)',order:0}]);
assert.equal(clean.length,1);
assert.equal(clean[0].id,'A');
assert.equal(sanitize({id:'x',name:'Ex',url:'https://example.com/',favorite:false},0).favorite,false);
assert.throws(()=>normalize({a:1}),/lista de sites/);
assert.throws(()=>normalize(Array.from({length:2001},(_,i)=>({id:String(i),name:'x',url:'https://x.com'}))),/Quantidade/);
console.log('PASSOU: validação URL, leitura de backup, duplicação, limite, versão SemVer');
